#!/usr/bin/env node
/**
 * Extracts the per-part checklist ("scope") from the NAVICORE OS Master Spec
 * into src/content/spec-scope.generated.ts, so scope lists are never retyped by hand.
 *
 * Usage:  node scripts/extract-spec-scope.mjs <path-to-NAVICORE-OS-MASTER-SPEC.md>
 *
 * The spec is confidential. It is read from the path you pass and is NOT copied
 * into this repository. Only the checklist item names are written out.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const specPath = process.argv[2];
if (!specPath) {
  console.error("Usage: node scripts/extract-spec-scope.mjs <path-to-spec.md>");
  process.exit(1);
}
const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../src/content/spec-scope.generated.ts");

const lines = readFileSync(specPath, "utf8").split(/\r?\n/);
const clean = (s) => s.replace(/\*\*/g, "").replace(/`/g, "").trim();

/** @type {Record<number,{number:number,specTitle:string,notes:string[],groups:{label:string|null,kind:string,items:string[]}[]}>} */
const parts = {};
let cur = null;
let group = null;
let inCode = false;

const newGroup = (label, kind = "scope", fromHeading = false) => {
  group = { label, kind, items: [], fromHeading };
  cur.groups.push(group);
};

// Readable display labels for lead-ins that read like developer notes in the spec.
const LABELS = {
  "Owner — Full authority, including": "Owner: full authority, including",
  "Super Admin — Almost everything operationally, but cannot": "Super Admin: almost everything operationally, but cannot",
  "NAVICORE Control Center — Only NAVICORE Owner can": "NAVICORE Control Center: only the NAVICORE Owner can",
  "Employee Approval — When HR approves a new employee": "When HR approves a new employee",
  "Because NAVICORE's vision includes personal operating systems": "Planned Personal OS scope",
  "Architecture should be ready for": "Architecture is designed to be ready for",
  "Owner/Super Admin": "What the Owner and Super Admin can see",
  '"What Happened Today?"': "What happened today?",
  "Owner/Super Admin Overview": "Owner and Super Admin overview",
  "Search authorized information across": "Search, limited to what you are authorized to see, across",
};
const tidy = (l) => (l == null ? l : LABELS[l] ?? l);
const kindFor = (text) =>
  /cannot|can't|must not/i.test(text) ? "limits" : /^future\b/i.test(text) ? "future" : "scope";

for (const raw of lines) {
  const line = raw.trimEnd();
  if (line.startsWith("```")) { inCode = !inCode; continue; }
  if (inCode) continue;

  const part = line.match(/^# PART (\d\d) — (.+)$/);
  if (part) {
    const n = Number(part[1]);
    cur = n >= 1 && n <= 52 ? (parts[n] = { number: n, specTitle: clean(part[2]), notes: [], groups: [] }) : null;
    group = null;
    continue;
  }
  if (!cur) continue;
  if (/^---\s*$/.test(line) || line === "") continue;

  const h = line.match(/^(#{2,3}) (.+)$/);
  if (h) { newGroup(clean(h[2]), "scope", true); continue; }

  const item = line.match(/^- \[ \] (.+)$/);
  if (item) {
    if (!group) newGroup(null);
    group.items.push(clean(item[1]));
    continue;
  }

  // plain text: a lead-in label ("Future:", "Features:") opens a group; other text is a note
  const text = clean(line);
  if (text.endsWith(":")) {
    const label = text.slice(0, -1);
    if (group && group.fromHeading && group.items.length === 0) {
      // "### Owner" followed by "Full authority, including:" -> one combined group
      group.label = `${group.label} — ${label}`;
      group.kind = kindFor(label);
      group.fromHeading = false;
    } else newGroup(label, kindFor(label));
    continue;
  }
  if (group && /cannot|can't/i.test(text) && group.items.length === 0) group.kind = "limits";
  cur.notes.push(text);
}

const nums = Object.keys(parts).map(Number).sort((a, b) => a - b);
let ts = `/* AUTO-GENERATED by scripts/extract-spec-scope.mjs — do not edit by hand.\n * Source: NAVICORE OS Master Reference v1.0 (checklist items only).\n * Note: every item in the guide is an unchecked "- [ ]" scope item. They describe\n * intended scope, not proof that a feature is shipped. Status lives in os-parts.ts. */\n\n`;
ts += `export type ScopeKind = "scope" | "limits" | "future";\n`;
ts += `export interface ScopeGroup { label: string | null; kind: ScopeKind; items: readonly string[] }\n`;
ts += `export interface SpecScope { number: number; specTitle: string; groups: readonly ScopeGroup[] }\n\n`;
ts += `export const specScope: Readonly<Record<number, SpecScope>> = {\n`;
for (const n of nums) {
  const p = parts[n];
  ts += `  ${n}: ${JSON.stringify({ number: p.number, specTitle: p.specTitle, groups: p.groups.filter((g) => g.items.length > 0).map((g) => ({ label: tidy(g.label), kind: g.kind, items: g.items })) })},\n`;
}
ts += `};\n`;
writeFileSync(out, ts);

console.log(`Parts found: ${nums.length}  (expected 52)`);
for (const n of nums) {
  const p = parts[n];
  const gs = p.groups.filter((g) => g.items.length);
  const total = gs.reduce((a, g) => a + g.items.length, 0);
  console.log(`${String(n).padStart(2, "0")} ${p.specTitle.slice(0, 38).padEnd(38)} items=${String(total).padStart(3)} groups=[${gs.map((g) => `${tidy(g.label) ?? "-"}${g.kind !== "scope" ? "(" + g.kind + ")" : ""}:${g.items.length}`).join(" | ")}]`);
}
console.log("\n--- notes worth reading (not emitted) ---");
for (const n of nums) if (parts[n].notes.length) console.log(String(n).padStart(2, "0"), "•", parts[n].notes.join(" ¶ ").slice(0, 230));
