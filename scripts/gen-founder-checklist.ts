/**
 * Builds FOUNDER-CHECKLIST.md: every open "[TODO: confirm with founder]" on the site, in one place.
 * Run: npm run checklist
 * Sources: src/content/global-todos.ts, each part's `todos` in os-parts.ts, UI copy in messages.ts,
 * and any marker left in code comments (found by scanning src/).
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { globalTodos } from "../src/content/global-todos";
import { moduleGroups } from "../src/content/module-groups";
import { en, TODO_PREFIX } from "../src/content/messages";
import { osParts } from "../src/content/os-parts";
import { STATUS_AS_OF } from "../src/content/site";

const strip = (s: string) => s.replace(TODO_PREFIX, "").trim();
const pad = (n: number) => String(n).padStart(2, "0");
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

const out: string[] = [];
const h = (s = "") => out.push(s);

h("# NAVICORE OS site: founder checklist");
h();
h("Generated by `npm run checklist`. Every item below is something the Master Reference does not settle, so the site either states nothing about it or labels it. Answer by editing `src/content/os-parts.ts` (part items), `src/content/messages.ts` (page copy) or the environment variables in `.env.example`, then re-run the checklist.");
h();

h("## 1. Decide before launch");
h();
for (const t of globalTodos.filter((x) => x.beforeLaunch)) h(`- [ ] **${t.id} ${t.topic}.** ${t.note}`);
h();
h("## 2. Decide when convenient");
h();
for (const t of globalTodos.filter((x) => !x.beforeLaunch)) h(`- [ ] **${t.id} ${t.topic}.** ${t.note}`);
h();

const noindex = osParts.filter((p) => !p.indexable);
h(`## 3. Pages that are noindex until you decide (${noindex.length} part pages, plus /partners and /privacy)`);
h();
h("These pages exist and work, but search engines are told not to index them and they are left out of the sitemap. Resolving the blocking item in `todos` (or removing `blocksIndexing`) makes a part page indexable.");
h();
for (const p of noindex) for (const t of p.todos.filter((x) => x.blocksIndexing)) h(`- [ ] **Part ${pad(p.number)} ${p.copy.en.name}** (\`/os/${p.slug}\`): ${strip(t.note)}`);
h("- [ ] **/partners**: noindex until the partner programme details are supplied (G08).");
h("- [ ] **/privacy**: noindex until legal review (G12).");
h();

h("## 4. Questions on individual parts");
h();
h("| Part | Page | Item | Question |");
h("| --- | --- | --- | --- |");
for (const p of osParts) for (const t of p.todos) h(`| ${pad(p.number)} | \`/os/${p.slug}\` | ${t.id}${t.blocksIndexing ? " (blocks indexing)" : ""} | ${cell(strip(t.note))} |`);
h();

h("## 5. Flow diagrams assembled by us (order not stated in the guide)");
h();
const composed = osParts.flatMap((p) => p.flows.filter((f) => f.source === "composed").map((f) => ({ p, f })));
const guideFlows = osParts.flatMap((p) => p.flows).filter((f) => f.source === "guide").length;
h(`${composed.length} of ${composed.length + guideFlows} flow diagrams arrange the guide's listed functions into a plain-language sequence. Each says so on its page. Please read them; correct any order that is wrong.`);
h();
for (const p of osParts) {
  const fs = p.flows.filter((f) => f.source === "composed");
  if (fs.length) h(`- Part ${pad(p.number)} ${p.copy.en.name}: ${fs.map((f) => `“${f.title}”`).join(", ")}`);
}
h();

h("## 6. Status labels to re-confirm");
h();
h(`Labels come from the guide as dated ${STATUS_AS_OF}. Live = screens shipped; In build = being built; Planned = specified, not in the current build; Later horizon = deliberately left for later; Foundation = shared layer or principle.`);
h();
for (const g of moduleGroups) {
  h(`**${g.name}**`);
  h();
  for (const p of osParts.filter((x) => x.group === g.id)) h(`- ${pad(p.number)} ${p.copy.en.name}: ${en.status[p.status].label}`);
  h();
}

h("## 7. Page copy that waits for your answer");
h();
const walk = (v: unknown, path: string, acc: [string, string][]) => {
  if (typeof v === "string") { if (v.startsWith(TODO_PREFIX)) acc.push([path, v]); }
  else if (Array.isArray(v)) v.forEach((x, i) => walk(x, `${path}[${i}]`, acc));
  else if (v && typeof v === "object") for (const [k, x] of Object.entries(v)) walk(x, path ? `${path}.${k}` : k, acc);
};
const uiTodos: [string, string][] = [];
walk(en, "", uiTodos);
for (const [path, text] of uiTodos) h(`- [ ] \`messages.${path}\`: ${strip(text)}`);
h();

h("## 8. Markers left in code");
h();
const files: string[] = [];
const scan = (dir: string) => {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) scan(full);
    else if (/\.(ts|tsx|css)$/.test(name)) files.push(full);
  }
};
scan("src");
const skip = new Set(["src/content/os-parts.ts", "src/content/messages.ts", "src/content/types.ts", "src/components/ui/TodoNotes.tsx", "src/content/global-todos.ts"]);
for (const f of files) {
  const rel = relative(".", f);
  if (skip.has(rel)) continue;
  readFileSync(f, "utf8").split("\n").forEach((line, i) => {
    const at = line.indexOf(TODO_PREFIX);
    if (at >= 0) h(`- [ ] \`${rel}:${i + 1}\`: ${line.slice(at + TODO_PREFIX.length).replace(/\*\/\s*$/, "").trim()}`);
  });
}
h();
writeFileSync("FOUNDER-CHECKLIST.md", out.join("\n"));
console.log(`FOUNDER-CHECKLIST.md written (${out.length} lines): ${globalTodos.length} global, ${osParts.reduce((n, p) => n + p.todos.length, 0)} part, ${uiTodos.length} page-copy items.`);
